// Generates ui/icons/MeiroIcons.kt from the path data in docs/android/mock/index.html
// (the P icon table and the LOGO svg strings), so the app uses the same glyphs as the mock.
// Run: node android/tools/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const html = fs.readFileSync(path.join(root, 'docs/android/mock/index.html'), 'utf8');
const out = path.join(root, 'android/app/src/main/kotlin/com/muratkirazkaya/meiro/ui/icons/MeiroIcons.kt');

const grab = name => {
  const i = html.indexOf(`const ${name} = {`);
  const j = html.indexOf('\n};', i);
  return vm.runInNewContext('(' + html.slice(html.indexOf('{', i), j + 2) + ')');
};
const P = grab('P');
const LOGO = grab('LOGO');
const cap = s => s.replace(/(^|[-_])([a-z])/g, (_, __, c) => c.toUpperCase());
const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

// Logo svg strings -> shapes. Only circle, path, rect (optionally inside <g fill>) occur.
function shapes(svg) {
  const res = [];
  const re = /<(circle|path|rect|g)\b([^>]*?)(\/?)>/g;
  let m, gfill = null;
  const attr = (a, k) => (a.match(new RegExp('\\b' + k + '="([^"]*)"')) || [])[1];
  while ((m = re.exec(svg))) {
    const [, tag, a] = m;
    if (tag === 'g') { gfill = attr(a, 'fill'); continue; }
    let d;
    if (tag === 'circle') {
      const cx = +attr(a, 'cx'), cy = +attr(a, 'cy'), r = +attr(a, 'r');
      d = `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
    } else if (tag === 'rect') {
      const x = +attr(a, 'x'), y = +attr(a, 'y'), w = +attr(a, 'width'), h = +attr(a, 'height'), r = +attr(a, 'rx') || 0;
      d = `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
    } else d = attr(a, 'd');
    res.push({ d, fill: attr(a, 'fill') ?? gfill, stroke: attr(a, 'stroke'), sw: attr(a, 'stroke-width') });
  }
  return res;
}
const color = c => {
  let h = c.replace('#', '');
  if (h.length === 3) h = [...h].map(x => x + x).join('');
  return '0xFF' + h.toUpperCase();
};

let kt = `// GENERATED by android/tools/gen-icons.mjs from docs/android/mock/index.html. Do not edit.
@file:Suppress("ktlint", "MagicNumber")

package com.muratkirazkaya.meiro.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

private fun glyph(name: String, d: String): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).addPath(
        PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.Black),
    ).build()

/** Material glyphs, one per entry of the mock's P table (24x24, filled black; tint at use). */
object MeiroIcons {
`;
for (const [k, d] of Object.entries(P)) kt += `    val ${cap(k)}: ImageVector by lazy { glyph("${k}", "${esc(d)}") }\n`;
kt += `}\n\n/** Source logos from the mock's LOGO table (multi-colour, not tinted). */\nobject MeiroLogos {\n`;
for (const [k, svg] of Object.entries(LOGO)) {
  kt += `    val ${cap(k)}: ImageVector by lazy {\n        ImageVector.Builder("logo:${k}", 24.dp, 24.dp, 24f, 24f).apply {\n`;
  for (const s of shapes(svg)) {
    const nodes = `PathParser().parsePathString("${esc(s.d)}").toNodes()`;
    if (s.stroke) kt += `            addPath(${nodes}, stroke = SolidColor(Color(${color(s.stroke)})), strokeLineWidth = ${s.sw}f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)\n`;
    else kt += `            addPath(${nodes}, fill = SolidColor(Color(${color(s.fill)})))\n`;
  }
  kt += `        }.build()\n    }\n`;
}
kt += '}\n';
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, kt);
console.log('wrote', out, Object.keys(P).length, 'icons', Object.keys(LOGO).length, 'logos');
