// Generates ui/theme/MeiroColors.kt and the day/night window colours from docs/android/mock/tokens.json.
// Run: node android/tools/gen-theme.mjs   (from anywhere)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'docs/android/mock/tokens.json'), 'utf8'));
const outKt = path.join(root, 'android/app/src/main/kotlin/com/muratkirazkaya/meiro/ui/theme/MeiroColors.kt');

const camel = n => n.replace(/^--/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
function argb(v) {
  v = v.trim();
  let m = v.match(/^#([0-9a-f]{6})$/i);
  if (m) return '0xFF' + m[1].toUpperCase();
  m = v.match(/^rgba?\(([^)]+)\)$/);
  if (m) {
    const p = m[1].split(',').map(s => parseFloat(s));
    const a = Math.round((p[3] ?? 1) * 255);
    const h = n => n.toString(16).padStart(2, '0').toUpperCase();
    return '0x' + h(a) + h(p[0]) + h(p[1]) + h(p[2]);
  }
  return null;
}
const names = Object.keys(tokens.vars.light).filter(k => argb(tokens.vars.light[k].value));
const fields = names.map(camel);
let kt = `// GENERATED by android/tools/gen-theme.mjs from docs/android/mock/tokens.json. Do not edit.
package com.muratkirazkaya.meiro.ui.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
class MeiroColors(
${fields.map(f => `    val ${f}: Color,`).join('\n')}
)

`;
for (const theme of ['light', 'dark']) {
  kt += `val ${theme === 'light' ? 'LightMeiroColors' : 'DarkMeiroColors'} = MeiroColors(\n`;
  for (const n of names) kt += `    ${camel(n)} = Color(${argb(tokens.vars[theme][n].value)}),\n`;
  kt += ')\n\n';
}
kt += `/** Body defaults from the mock: ${tokens.body.fontSize} / ${tokens.body.lineHeight}, letter-spacing ${tokens.body.letterSpacing}. */\n`;
kt += `const val BodyFontSizeSp = ${parseFloat(tokens.body.fontSize)}f\nconst val BodyLineHeightSp = ${parseFloat(tokens.body.lineHeight)}f\nconst val BodyLetterSpacingSp = ${parseFloat(tokens.body.letterSpacing)}f\n`;
fs.mkdirSync(path.dirname(outKt), { recursive: true });
fs.writeFileSync(outKt, kt);

// Window background for the pre-Compose frame, per theme.
const resRoot = path.join(root, 'android/app/src/main/res');
for (const [dir, theme] of [['values', 'light'], ['values-night', 'dark']]) {
  fs.mkdirSync(path.join(resRoot, dir), { recursive: true });
  const c = tokens.vars[theme]['--surface'].value;
  fs.writeFileSync(path.join(resRoot, dir, 'meiro_colors.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by android/tools/gen-theme.mjs. Do not edit. -->\n<resources>\n    <color name="meiro_surface">${c}</color>\n</resources>\n`);
}
console.log('wrote', outKt, 'colors:', names.length);
